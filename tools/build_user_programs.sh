# Build the user-mode programs that the kernel embeds as fixtures.
#
# Output: kernel/kernel/src/user/prog/<name>.elf, which `user::programs`
# includes with include_bytes!. Run this after touching anything under
# apps/user/, and commit the result — the kernel build has no way to invent
# the file, and a missing one is a compile error rather than a stale binary.
#
# The syscall numbers are *generated* from the kernel's own enum rather than
# written down here. A hand-maintained copy drifts the first time a call is
# added, and the symptom is a program that calls `close` and lands in `read`.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
gcc="${RISCV_GCC:-/opt/xpack-riscv-none-elf-gcc-14.2.0-3/bin/riscv-none-elf-gcc}"
out_dir="$root/kernel/kernel/src/user/prog"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [ ! -x "$gcc" ]; then
    echo "error: no RISC-V gcc at $gcc (set RISCV_GCC)" >&2
    exit 1
fi

# --- syscall numbers, straight from kernel/header/src/lib.rs ---
python3 - "$root/kernel/header/src/lib.rs" "$tmp/nr.h" <<'PY'
import re, sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
body = re.search(r"pub enum NR \{(.*?)\n    \}", text, re.S)
if not body:
    sys.exit("could not find the NR enum")

# Enum variants may carry a doc comment or a `#[repr]`-style attribute; take the
# identifier that starts a line and skip anything ending in a comma-less token
# such as `LastNR`.
names = []
for line in body.group(1).splitlines():
    line = line.strip()
    if not line or line.startswith("//"):
        continue
    m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*),?$", line)
    if m:
        names.append(m.group(1))

if "LastNR" in names:
    names = names[: names.index("LastNR")]

with open(dst, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/build_user_programs.sh — do not edit. */\n")
    f.write("#ifndef BLUEOS_NR_H\n#define BLUEOS_NR_H\n\n")
    for i, name in enumerate(names):
        # CamelCase -> SCREAMING_SNAKE, matching the kernel enum order.
        snake = re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()
        f.write(f"#define __NR_{snake.lower()} {i}\n")
    f.write("\n#endif\n")
print(f"generated {len(names)} syscall numbers")
PY

mkdir -p "$out_dir"

build() {
    local name="$1" src="$2"
    "$gcc" \
        -march=rv64imac_zicsr -mabi=lp64 -mcmodel=medany \
        -nostdlib -nostartfiles -ffreestanding -fno-builtin \
        -fno-zero-initialized-in-bss \
        -fno-stack-protector -fno-pic -no-pie \
        -O2 -Wall -Wextra -Werror \
        -I"$tmp" \
        -T "$(dirname "$src")/link.ld" \
        -Wl,--build-id=none -Wl,--no-relax \
        -o "$out_dir/$name.elf" "$src"
    echo "built $out_dir/$name.elf ($(stat -c%s "$out_dir/$name.elf") bytes)"
}

build hello "$root/apps/user/hello/hello.c"
build proc "$root/apps/user/proc/proc.c"
build posix_u "$root/apps/user/posix_u/posix_u.c"

# Sanity: the loader requires the entry point inside the first LOAD segment and
# the image to start at USER_IMAGE_BASE. Fail here rather than in QEMU.
"${READELF:-$(dirname "$gcc")/riscv-none-elf-readelf}" -l "$out_dir/hello.elf" |
    awk '/LOAD/ {print "  segment: " $0}'
